import { test, expect } from "@playwright/test";
import { registerThroughApi } from "./helpers";

test.use({ actionTimeout: 15000 });
test("демонстрационная Элирия содержит связанных героев и события и создаётся один раз", async ({ page }, testInfo) => {
  await registerThroughApi(page.request);
  await page.goto("/");
  await page.getByRole("button", { name: "Открыть демомир", exact: false }).click();
  await expect(page.getByRole("heading", { name: "Элирия", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Лиора Эльвейн", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Аэрен Вальд", exact: true })).toBeVisible();
  await expect(page.getByText("Великое затмение", { exact: true })).toBeVisible();
  const worldsResponse = await page.request.get(`/api/projects/${await page.getByRole("combobox", { name: "Текущий проект" }).inputValue()}/worlds`);
  expect(worldsResponse.ok()).toBe(true);
  const { worlds } = await worldsResponse.json();
  const worldResponse = await page.request.get(`/api/worlds/${worlds[0].id}`);
  const data = await worldResponse.json();
  expect(data.characters).toHaveLength(3);
  expect(data.events).toHaveLength(3);
  expect(data.relations).toHaveLength(2);
  expect(data.events.some((event: { characterIds: string[] }) => event.characterIds.length === 3)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("overview.png"), fullPage: true });
  await page.screenshot({ path: "/tmp/lore-studio-overview.png", fullPage: true });
  await page.getByRole("button", { name: "Все персонажи", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Мира Солвей", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Мои проекты", exact: false }).click();
  await page.getByRole("button", { name: "Открыть демомир", exact: false }).click();
  await expect(page.getByRole("heading", { name: "Элирия", exact: true })).toBeVisible();
  const projectsResponse = await page.request.get("/api/projects");
  expect((await projectsResponse.json()).projects).toHaveLength(1);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Элирия", exact: true })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("navigation", { name: "Разделы мира" }).getByRole("button", { name: "Персонажи", exact: true }).click();
  await page.getByRole("button").filter({ has: page.getByRole("heading", { name: "Лиора Эльвейн", exact: true }) }).click();
  const editor = page.getByRole("dialog", { name: "Карточка персонажа" });
  await expect(editor).toBeVisible();
  await editor.getByRole("tab", { name: "История и характер" }).click();
  const biography = `${await editor.getByRole("textbox", { name: "Биография", exact: true }).inputValue()} Проверено с мобильного устройства.`;
  await editor.getByRole("textbox", { name: "Биография", exact: true }).fill(biography);
  await editor.getByRole("button", { name: "Сохранить", exact: true }).click();
  await expect(editor).toHaveCount(0);
  await page.reload();
  await page.getByRole("navigation", { name: "Разделы мира" }).getByRole("button", { name: "Персонажи", exact: true }).click();
  await page.getByRole("button").filter({ has: page.getByRole("heading", { name: "Лиора Эльвейн", exact: true }) }).click();
  await page.getByRole("dialog").getByRole("tab", { name: "История и характер" }).click();
  await expect(page.getByRole("dialog").getByRole("textbox", { name: "Биография", exact: true })).toHaveValue(biography);
});
